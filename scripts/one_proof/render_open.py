"""Render docs/one-proof/OPEN.md from the Lean data and the two tables.

Inputs (run from the repository root):
* docs/one-proof/open-statements.json, written by `lake env lean scripts/one_proof/OpenStatements.lean`
  (the open hypotheses of ZInQ.OneProof.frozenTarget, read off the Lean build);
* docs/one-proof/kinds.tsv, the classification of each hypothesis (the source of truth for counts);
* docs/one-proof/claims.tsv, who is working on what.

Usage: python3 scripts/one_proof/render_open.py [--check]
With --check, exit 1 if the JSON and kinds.tsv disagree on the set of hypotheses (a fold that changed the
open hypotheses without updating kinds.tsv), without writing anything.
"""
import csv, json, sys
from collections import Counter

D = 'docs/one-proof/'
data = json.load(open(D + 'open-statements.json'))
hyps = data['hypotheses']
kinds = {r['field']: r for r in csv.DictReader(open(D + 'kinds.tsv'), delimiter='\t')}
claims = {}
for r in csv.DictReader(open(D + 'claims.tsv'), delimiter='\t'):
    claims.setdefault(r['field'], []).append(r)

h_fields = [h['field'] for h in hyps if h['bundle'] != 'frozenTarget']
others = {h['field'] for h in hyps if h['bundle'] == 'frozenTarget'}
unknown = sorted(set(claims) - set(h_fields) - others)
if unknown:
    print('claims.tsv names no open hypothesis:', unknown)
    sys.exit(1)
missing = sorted(set(h_fields) - set(kinds))
stale = sorted(set(kinds) - set(h_fields))
if missing or stale:
    print('kinds.tsv out of date: not classified:', missing, '; no longer open:', stale)
    sys.exit(1)
if '--check' in sys.argv:
    print(f'ok: {len(h_fields)} bundle fields, all classified')
    sys.exit(0)

n = len(h_fields)
strict = Counter(kinds[f]['strict'] for f in h_fields)
strictest = Counter(kinds[f]['strictest'] for f in h_fields)
by_kind = Counter(kinds[f]['kind'] for f in h_fields)

def claim_text(f):
    cs = claims.get(f, [])
    if not cs:
        return 'open: no one is on it'
    parts = []
    for c in cs:
        s = f"{c['task']}: {c['status']} (since {c['since']})"
        if c['issue']:
            repo, num = c['issue'].split('#')
            s += f" [issue #{num}](https://github.com/{repo}/issues/{num})"
        parts.append(s)
    return '; '.join(parts)

def anchor(f):
    return f.lower()

out = []
w = out.append
w('# Open statements of the single proof')
w('')
w('<!-- Generated by scripts/one_proof/render_open.py from open-statements.json (the Lean build), kinds.tsv and')
w('claims.tsv. Do not edit by hand: edit kinds.tsv or claims.tsv, or regenerate the JSON after a fold. -->')
w('')
w('`ZInQ.OneProof.frozenTarget` (`ZInQKernel/OneProof/Main.lean`) is a Lean theorem, checked by the kernel with no')
w('`sorry` and only the standard axioms, that proves the frozen target `ZInQ.FrozenTarget`, the theorem that Z is')
w('Diophantine in Q (the 11/5 manuscript, Theorem 1.1), from the hypotheses below. Everything else is proved.')
w('Each hypothesis is a Lean `Prop`; proving one in Lean, or reducing it to statements printed in the literature,')
w('removes it. See')
w('[CONTRIBUTING.md](CONTRIBUTING.md) for how to contribute and check a proof.')
w('')
w(f'**{n} hypotheses of the H part** (in the bundles `{"`, `".join(sorted({h["bundle"] for h in hyps if h["bundle"] != "frozenTarget"}))}`), '
  f'plus {len(hyps) - n} hypotheses of the Tian–Yuan–Zhang and Gross–Zagier parts listed at the end.')
w('')
w(f'* **Strict count: {strictest["LEAF"]} published / {strictest["GLUE"]} glue** (the strictest flagged reading; '
  f'{strict["LEAF"]}/{strict["GLUE"]} without the one strictest-reading flag).')
w('* LEAF means a published, refereed theorem stated over genuine definitions in its printed form, or a consequence')
w('  of it that is never stronger. GLUE is everything else: a consequence of one theorem, a composite of several,')
w('  project glue, or a leaf whose published form is still pending a reading (`kinds.tsv`, column `flag`).')
w(f'* By kind: ' + ', '.join(f'{k} {v}' for k, v in sorted(by_kind.items())) + '.')
w('')
w('## Index')
w('')
w('| hypothesis | bundle | kind | strict | flag | status |')
w('| --- | --- | --- | --- | --- | --- |')
order = sorted(h_fields, key=lambda f: (kinds[f]['strictest'] != 'GLUE', kinds[f]['bundle'], f.lower()))
for f in order:
    k = kinds[f]
    status = 'open' if f not in claims else claims[f][0]['task']
    w(f"| [`{f}`](#{anchor(f)}) | {k['bundle']} | {k['kind']} | {k['strictest']} | {k['flag']} | {status} |")
w('')
w('## The hypotheses')
w('')
hmap = {h['field']: h for h in hyps}
for f in order:
    h, k = hmap[f], kinds[f]
    w(f'### {f}')
    w('')
    w(f"* Bundle field `HDec.HSyn.{h['bundle']}.{f}`; kind **{k['kind']}**, strict **{k['strictest']}**"
      + (f"; flag: {k['flag']}" if k['flag'] else '') + '.')
    w(f"* Source: {k['source']}")
    w(f"* Status: {claim_text(f)}.")
    w('')
    w('```lean')
    w(h['type'])
    w('```')
    if h['docstring'].strip():
        w('')
        for line in h['docstring'].strip().splitlines():
            w('> ' + line.strip())
    w('')
w('## Tian–Yuan–Zhang and Gross–Zagier hypotheses')
w('')
w('These are `frozenTarget`\'s other arguments (outside the H bundles). They are tracked in the TYZ and GZ issues.')
w('')
for h in hyps:
    if h['bundle'] != 'frozenTarget':
        continue
    w(f"### {h['field']}")
    w('')
    w(f"* Status: {claim_text(h['field'])}.")
    w('')
    w('```lean')
    w(h['type'])
    w('```')
    w('')
open(D + 'OPEN.md', 'w').write('\n'.join(out))
print(f'wrote {D}OPEN.md: {n} H hypotheses, strictest {strictest["LEAF"]}/{strictest["GLUE"]}, {len(hyps) - n} others')
