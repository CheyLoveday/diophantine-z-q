"""From the base source, emit a scratch bypass. Writes only under scratch/deligne-narrow.

Copy the three branches where the Deligne value is passed as a whole. Keep
the original conversions below their final consumers. The only new top-level
field is the replacement for the former Deligne input. The Main body and all
its other binders are copied verbatim.
"""
from collections import Counter
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True

import copylib
HERE = Path("scratch/deligne-narrow")
H = Path("ZInQKernel/OneProof/H")
MAIN = Path("ZInQKernel/OneProof/Main.lean")
FILES = [H / f"Y3Copy{i}.lean" for i in range(1, 7)] + [H / "Y3Open.lean", H / "TailZ89.lean"]
TOP = "sixContactMin_of_open82"
OLD = "deligneCanonicalModelY3EveryPrint"
NEW = "deligneCanonicalModelY3Narrow"
MID = "shimuraMainThmIDeligneY3AbU"

# Mask comments while preserving their line breaks, including nested Lean comments.
def uncomment(s):
    return re.sub(r"/-(?:(?!/-)[\s\S])*?-/", lambda m: "\n" * m[0].count("\n"), s)

def clean(s):
    while "/-" in s:
        t = uncomment(s)
        if t == s:
            raise ValueError("unclosed comment")
        s = t
    s = re.sub(r"(?m)^ *--[^\n]*\n", "", s)
    return "\n".join(line.rstrip() for line in s.splitlines())

def unique_replace(s, old, new):
    if s.count(old) != 1:
        raise ValueError(f"expected one occurrence: {old}")
    return s.replace(old, new)

def short(name):
    return name.split(".")[-1]

nodes = {}
for f in map(str, FILES):
    for i, line in enumerate(copylib.lines(f)):
        if copylib.mask(f)[i]:
            continue
        m = re.match(r"^(?:(?:private|protected|noncomputable) )*(theorem|lemma|structure|def|abbrev) (\S+)", line)
        if m is None:
            continue
        k, name = m.groups()
        if "." in name.removeprefix("_root_.HDec.HSyn.GR9.").removeprefix("_root_.HDec.HSyn."):
            continue  # only named H bundle-level declarations can carry this field
        _, e = copylib.decl_extent(f, i)
        if short(name) in nodes:
            raise ValueError(f"duplicate declaration {name}")
        nodes[short(name)] = (k, f, i, name, clean("\n".join(copylib.lines(f)[i:e])))

all_names = set(nodes)
deps = {
    n: set(re.findall(r"[\w'!?₀-₉]+", code)) & all_names - {n}
    for n, (_, _, _, _, code) in nodes.items()
}
carriers = {n for n, (k, _, _, _, code) in nodes.items()
            if k == "structure" and re.search(rf"(?m)^  ({OLD}|{MID}) :", code)}
tainted = set(carriers)
while True:
    new = {n for n in nodes if deps[n] & tainted} - tainted
    if not new:
        break
    tainted |= new
assert TOP in tainted

visit = [TOP]
needed = set()
while visit:
    n = visit.pop()
    if n in needed or n not in tainted:
        continue
    needed.add(n)
    visit.extend(deps[n])

ren = {n: n + ("N" if n in carriers else "_dn") for n in needed}
ren[TOP] = "sixContactMin_of_open83"
ren["OpenResearchLeaves63"] = "OpenResearchLeaves64"
ren["openResearchLeaves60_y3x6_of_OpenResearchLeaves63"] = "openResearchLeaves60_y3x6N_of_OpenResearchLeaves64"

def edit_code(s):
    s = re.sub(rf"(?m)^(  {OLD} : )_root_\.Y3Hodge\.DeligneCanonicalModelY3EveryPrint$",
               "  " + NEW + " : _root_.Y3Hodge.DeligneCanonicalModelY3Narrow", s)
    s = s.replace(OLD + " := n." + OLD, NEW + " := n." + NEW)
    s = re.sub(rf"(?m)^  {MID} : _root_\.RayClassCFT\.ShimuraMainThmIDeligneY3AbU$",
               "  deligneReadData : _root_.Y3Hodge.ReadData", s)
    if "_root_.Y3Hodge.deligneH_of_print" in s:
        s = unique_replace(s,
            f"  {MID} := (_root_.Y3Fix.shimuraMainThmIDeligneY3AbU_of_print "
            "_root_.ZInQ.Contrib.CloudB3W16Torsion.mumfordTorsionAlgClosed_proof n.y3FineModuliAbP "
            f"(_root_.Y3Hodge.deligneH_of_print n.{OLD}))",
            "  deligneReadData := _root_.Y3Hodge.readData_of_narrow\n"
            "    _root_.ZInQ.Contrib.CloudB3W16Torsion.mumfordTorsionAlgClosed_proof n.y3FineModuliAbP\n"
            f"    n.{NEW}")
    s = re.sub(rf"{MID} := (\w+)\.{MID}", r"deligneReadData := \1.deligneReadData", s)
    s = re.sub(rf"_root_\.RayClassCFT\.shimuraFamilyAb_of_U (\w+)\.{MID}",
               r"\1.deligneReadData.1", s)
    s = re.sub(rf"_root_\.RayClassCFT\.rayClassCMAb_of_leaves (\w+)\.{MID}",
               r"\1.deligneReadData.2.1", s)
    s = re.sub(rf"\(_root_\.DCY3Used\.y3ConnectedAb_of_U (\w+)\.{MID}\)",
               r"\1.deligneReadData.2.2", s)
    if any(x in s for x in [OLD, MID, "DeligneCanonicalModelY3EveryPrint", "ShimuraMainThmIDeligneY3AbU"]):
        raise ValueError("unreplaced Deligne reference:\n" + s)
    return copylib.rename(s, ren)

def generated():
    header = """import ZInQKernel.OneProof.Main
import ZInQKernel.Contrib.OneProof.DeligneNarrow

/-! Scratch bypass for the narrowed Deligne consequence. Generated by
`scratch/deligne-narrow/generate.py`. Existing declarations stay in place.
For integration, put the H part in the new tail and switch the headline to it. -/

section
set_option linter.all false
"""
    out = [header]
    manifest = []
    emitted = set()
    for n, (k, f, i, name, code) in nodes.items():
        if n not in needed:
            continue
        # The base generation already orders these declarations by dependence.
        if d := (deps[n] & needed) - emitted:
            raise ValueError(f"forward reference {n}: {sorted(d)}")
        scopes = copylib.context(f, i)
        out.extend([f"-- From {f}:{i+1}.", "section"])
        for op, _, cmds in scopes:
            if op:
                out.append(op)
            out += cmds
        out.append(edit_code(code).strip())
        out += [cl for _, cl, _ in reversed(scopes) if cl] + ["end", ""]
        emitted.add(n)
        manifest.append(f"{k}\t{f}:{i+1}\t{name}\t{ren[n]}")
    tail = "\n".join(out + ["end", "", "#print axioms HDec.HSyn.sixContactMin_of_open83", ""])
    tail = tail.replace("import ZInQKernel.OneProof.Main", "import ZInQKernel.OneProof.H.TailZ89", 1)
    text = MAIN.read_text().split("\nnamespace ZInQ.OneProof", 1)[1]
    body = text.split("theorem _root_.ZInQ.OneProof.frozenTarget", 1)[1].split("\nend ZInQ.OneProof", 1)[0].strip()
    body = edit_code(body)
    out.extend(["theorem ZInQ.OneProof.frozenTargetDeligneNarrow", body, "end", ""])
    for n in manifest:
        _, _, name, new = n.split("\t")
        if name.startswith("_root_."):
            full = name.removeprefix("_root_.").rsplit(".", 1)[0] + "." + new
        else:
            _, f, i, _, _ = nodes[short(name)]; ctx=copylib.context(f, i)
            ns = ".".join(o.removeprefix("namespace ") for o, _, _ in ctx if o.startswith("namespace "))
            full = ns + "." + new
        if not n.startswith("structure\t"):
            out.append("#print axioms " + full)
    out.extend(["#print axioms ZInQ.OneProof.frozenTargetDeligneNarrow",
                (HERE / "Closure.lean.txt").read_text()])
    return "\n".join(out), "\n".join(manifest) + "\n", tail

out, manifest, tail = generated()
if sys.argv[1:] == ["--tail-only"]:
    sys.stdout.write(tail)
elif not sys.argv[1:]:
    (HERE / "DryRun.lean").write_text(out)
    (HERE / "generated-declarations.tsv").write_text(manifest)
    print(f"Copied {len(needed)} declarations: {dict(Counter(nodes[n][0] for n in needed))}")
else:
    sys.exit("Usage: generate.py [--tail-only]")
