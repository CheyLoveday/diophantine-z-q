"""Generate scratch/flt-cqj/FoldBypass.lean: the H chain from leaf-fold7 to leaf-fold19 with the textbook field
`igusaGL2 : ZInQ.RLeaf.IgusaGL2` replaced by `cyclicQuotientJBijOn : CyclicQuotientJBijOn`.

Every declaration of OneProof/H/TailX..TailZ32 (inside `namespace HDec`/`namespace HSyn`) whose text mentions a
textbook bundle of generations 7-11 or an already copied declaration is copied with suffix `_cqj` (structures:
`OpenTextbookLeavesKCqj`); the only consumer of `igusaGL2` (`textbookLeaves6_of_open7`, field `x0Transitive`)
is filled from `x0Transitive_of_cyclicQuotientJBijOn`.  Run from the repository root."""
import re, sys
H = 'ZInQKernel/OneProof/H/'
files = ['TailX'] + ['TailZ%d' % i for i in range(4, 33)]
START = re.compile(r'^(theorem|def|structure|abbrev|lemma|noncomputable def|private theorem|instance)\s+([^\s(:]+)')
STOP = re.compile(r'^(namespace|end|section|open|#print|set_option|variable|attribute|noncomputable section|/-!)')

def blocks(fn):
    """(name, kind, text) for each top-level declaration inside HDec.HSyn."""
    L = open(H + fn + '.lean').read().split('\n')
    ns, out, i = [], [], 0
    while i < len(L):
        l = L[i]
        m = re.match(r'^namespace (\S+)', l)
        if m:
            ns.append(m.group(1)); i += 1; continue
        if re.match(r'^end(\s|$)', l) and not re.match(r'^end\s+--', l):
            if ns and l.strip() != 'end': ns.pop()
            i += 1; continue
        # docstring start or decl start
        j = i
        if l.startswith('/--'):
            while j < len(L) and not L[j].rstrip().endswith('-/'): j += 1
            j += 1
            while j < len(L) and L[j].startswith('@['): j += 1
        m = START.match(L[j]) if j < len(L) else None
        if m and '.'.join(ns) in ('HDec.HSyn', 'HDec.HSyn'):
            k = j + 1
            while k < len(L) and not (START.match(L[k]) or STOP.match(L[k]) or L[k].startswith('/--')):
                k += 1
            out.append((m.group(2), m.group(1), '\n'.join(L[i:k]).rstrip()))
            i = k; continue
        i += 1
    return out

names = {('OpenTextbookLeaves%d' % k): ('OpenTextbookLeaves%dCqj' % k) for k in range(7, 12)}
copied = []
for fn in files:
    for name, kind, text in blocks(fn):
        if name in names: pass
        elif any(re.search(r'(?<![\w.])' + re.escape(n) + r'(?![\w\'])', text) for n in names):
            names[name] = name + '_cqj'
        else:
            continue
        copied.append((fn, name, text))

def rename(text):
    for old, new in sorted(names.items(), key=lambda kv: -len(kv[0])):
        text = re.sub(r'(?<![\w.])' + re.escape(old) + r'(?![\w\'])', new, text)
    return text

out = []
for fn, name, text in copied:
    t = rename(text)
    t = t.replace('igusaGL2 : _root_.ZInQ.RLeaf.IgusaGL2',
                  'cyclicQuotientJBijOn : _root_.ZInQ.Contrib.CloudB2X0Transitive.CyclicQuotientJBijOn')
    t = re.sub(r'igusaGL2 := (\w+)\.igusaGL2', r'cyclicQuotientJBijOn := \1.cyclicQuotientJBijOn', t)
    t = t.replace('_root_.CurveSplit.x0Transitive_of_igusaGL2 t.igusaGL2',
                  '_root_.ZInQ.Contrib.CloudB2X0Transitive.x0Transitive_of_cyclicQuotientJBijOn t.cyclicQuotientJBijOn')
    if 'igusaGL2' in t:
        sys.exit('unhandled igusaGL2 in ' + name)
    out.append('-- copied from %s.lean: %s\n%s' % (fn, name, t))

hdr = '''import ZInQKernel.OneProof.H.TailZ32
import ZInQKernel.Contrib.CloudB2X0Transitive.Reduction

/-! # flt-cqj: the H chain with Igusa's theorem replaced by the cyclic-quotient bijection (bypass fold check)

Generated by `scratch/flt-cqj/gen_bypass.py` from `ZInQKernel/OneProof/H/TailX.lean`..`TailZ32.lean`: every
declaration that reads a textbook bundle of leaf-folds 7-19 (`OpenTextbookLeaves7`..`OpenTextbookLeaves11`) is
copied with suffix `_cqj`, the bundles with the field `igusaGL2 : ZInQ.RLeaf.IgusaGL2` replaced by
`cyclicQuotientJBijOn : ZInQ.Contrib.CloudB2X0Transitive.CyclicQuotientJBijOn` (Anthropic FLT's
`bijOn_cyclicQuotientJ_isRoot_modularPolynomial_of_transcendental_j`, universe 0). The one consumer of
`igusaGL2`, the field `x0Transitive` of `OpenTextbookLeaves6`, is filled by
`x0Transitive_of_cyclicQuotientJBijOn`. Bodies are otherwise copied verbatim. No `sorry`. -/

namespace HDec

set_option maxHeartbeats 1000000

namespace HSyn

open CategoryTheory AlgebraicGeometry Limits MonoidalCategory CartesianMonoidalCategory MonObj

'''
ftr = '''

end HSyn

end HDec

#print axioms HDec.HSyn.sixContactMin_of_open26_cqj
'''
open(sys.argv[1], 'w').write(hdr + '\n\n'.join(out) + ftr)
print(len(copied), 'declarations copied:', ' '.join(n for _, n, _ in copied))
