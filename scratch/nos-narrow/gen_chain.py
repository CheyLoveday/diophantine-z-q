"""Replay the copy bypass from Taint.lean's output (fold-c8 + d2a6b).
Run from repository root: python3 -B scratch/nos-narrow/gen_chain.py TAINT NOSNarrowChain.lean.
"""
from pathlib import Path
import re
import sys

import copylib
from copylib import context, emit, find_decl

BASE = 'ZInQKernel.OneProof.H.TailZ87'
TOP = 'HDec.HSyn.sixContactMin_of_open80'
SEEDS = ('r7a', 'neronOggShafarevichSep')
FIELD = '|'.join(SEEDS)
KINDS = ('theorem', 'lemma', 'def', 'abbrev', 'instance')
FORWARD = '_root_.NOSNarrow.nosForward_proof'
READERS = ("kernelFieldExists_of_split_hf_u''", 'modelG3G6_of_leaves3U')
AUTO = {
    'mk', 'rec', 'recOn', 'casesOn', 'brecOn', 'below', 'noConfusion', 'noConfusionType', 'eta',
    'mk.injEq', 'mk.inj', 'ext', 'ext_iff',
}
HEADER = '''import ZInQKernel.OneProof.H.TailZ87
import ZInQKernel.Contrib.OneProof.NOSNarrow

/-! # OneProof H without the Néron–Ogg–Shafarevich field

Generated by `scratch/nos-narrow/gen_chain.py`. This is the dependency chain of
`HDec.HSyn.sixContactMin_of_open80` with the old NOS fields omitted. The kernel field and
A6 use the proved forward implication at their only two call sites. Every original
declaration is unchanged.
-/

set_option linter.style.longLine false
set_option linter.style.haveILetI false
'''

def modfile(mod):
    return mod.replace('.', '/') + '.lean'

def namespace_at(f, i):
    return '.'.join(op.removeprefix('namespace ') for op, _, _ in context(f, i)
                    if op.startswith('namespace '))

def module_order():
    seen, order = set(), []
    def visit(m):
        if m in seen:
            return
        seen.add(m)
        file = Path(modfile(m))
        if not m.startswith('ZInQKernel.') or not file.is_file():
            return
        for imp in re.findall(r'^(?:(?:public|private|meta) )*import (?:all )?([\w.]+)', file.read_text(), re.M):
            visit(imp)
        order.append(str(file))
    sys.setrecursionlimit(100_000)
    visit(BASE)
    return {f: i for i, f in enumerate(order)}

def qualified_decl(f, full, kinds):
    parts = full.split('.')
    for i in reversed(range(len(parts))):
        short = '.'.join(parts[i:])
        ns = '.'.join(parts[:i])
        hits = find_decl(f, short, kinds)
        for which, idx in enumerate(hits):
            if namespace_at(f, idx) == ns:
                return (idx, f, short, which, kinds, full)
    return None

def parse(path):
    carriers = {}
    tainted = {}
    for line in Path(path).read_text().splitlines():
        m = re.match(r'^([TSC]) (\S+) (\S+)', line)
        if m:
            kind, mod, n = m.groups()
            (carriers if kind == 'C' else tainted)[n] = mod
    assert TOP in tainted, 'Taint missing its active chain top'
    assert 'HDec.HSyn.ResearchLeaves3EBU' in carriers, 'Taint missing the carrier with an unused seed'
    return carriers, tainted

def strip_field(s):
    s2, n = re.subn(r'(?m)(^  /--(?:(?!-/)[\s\S])*?-/\n)?^  (?:' + FIELD +
                    r') : [^\n]*\n(?:^    [^\n]*\n)*', '', s)
    assert n == 1, ('expected one seed field', n, s[:200])
    return s2

def strip_assign(s):
    return re.subn(r'(?m)^([ ]+)(?:' + FIELD + r') :=[^\n]*\n(?:^\1 +[^\n]*\n)*', '', s)

def rename_short(short, structure):
    return short + ('NOS' if structure else '_nos')

def main():
    carriers, tainted = parse(sys.argv[1])
    rank = module_order()
    rows = []
    excluded = []
    reader_names = {s: s + '_nos' for s in READERS}
    for full, mod in sorted((carriers | tainted).items()):
        if mod == 'ZInQKernel.OneProof.Main':
            continue
        f = modfile(mod)
        is_struct = full in carriers
        if f not in rank:
            raise SystemExit(f'{full} outside the import tree: {f}')
        decl = qualified_decl(f, full, ('structure',) if is_struct else KINDS)
        if decl is None:
            parent = next((c for c in carriers if full.startswith(c + '.')), None)
            if parent or ('._' in full) or full.startswith('_private.'):
                excluded.append((full, 'generated or private'))
                continue
            raise SystemExit(f'cannot locate {full} in {f}')
        rows.append(decl)
    ren = dict(reader_names)
    for _, _, s, _, k, full in rows:
        new = rename_short(s.rsplit('.', 1)[-1], k == ('structure',))
        prefix = full[:len(full) - len(s)]
        if '.' in s and full.rsplit('.', 1)[0] in carriers:
            # A dot-notation method moves to the new structure's namespace, keeping its short name.
            parent, method = s.rsplit('.', 1)
            short_new = parent + 'NOS.' + method
        else:
            short_new = '.'.join(s.split('.')[:-1] + [new])
        for key, value in [(full, prefix + short_new), (s, short_new)]:
            old = ren.setdefault(key, value)
            assert old == value, (full, key, old, value)
    blocks, seen_top, notes = [], {'set_option linter.style.longLine false',
                                    'set_option linter.style.haveILetI false'}, []
    replaced = 0
    deleted = 0
    for idx, f, s, which, k, full in sorted(rows, key=lambda x: (rank[x[1]], x[0])):
        txt = emit(f, s, ren, kinds=k, which=which, seen_top=seen_top)
        if k == ('structure',):
            txt = strip_field(txt)
            assert full in carriers
        else:
            txt, n = strip_assign(txt)
            deleted += n
            for reader, before in zip(READERS, ('t.t6', 'hFS')):
                target = f"{reader}_nos {before} r.r7a"
                n = txt.count(target)
                if n:
                    assert s == 'gluePieces_of_open4_hf_pz_eb_u_c8' and n == 1
                    txt = txt.replace(target, f"{reader}_nos {before} {FORWARD}")
                    replaced += n
        # Check identifiers in code only. Old explanatory comments may refer to the base.
        code = re.sub(r'/-[\s\S]*?-/', '', txt)
        code = re.sub(r'(?m)--.*$', '', code)
        assert not re.search(r'(?<![\w\'])(?:' + FIELD +
                             r'|NeronOggShafarevich(?:Sep)?|neronOggShafarevich_of_sep)(?![\w\'])', code), (full, code)
        blocks.append(txt)
        notes.append(f'{f}:{idx + 1} {full} → {ren[full]}')
    assert replaced == 2
    Path(sys.argv[2]).write_text(HEADER + '\n' + '\n'.join(blocks) +
                                 f'\n#print axioms {TOP}_nos\n')
    print(f'{len(rows)} declarations, {len(carriers)} structures; {deleted} assignments deleted; {replaced} terminal calls')
    for note in notes:
        print(note)
    for n, reason in excluded:
        print(f'skip {n}: {reason}')

if __name__ == '__main__':
    main()
