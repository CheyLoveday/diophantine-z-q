"""Port the assembled CM fibre split to open77, retaining its GR9 route.

Usage: python3 scratch/cm-curve-order/gen_fold.py > Fold.lean
Run from the worktree root. The only new declarations are the reduced CM input
bundle, the theorem path from open4 to open77, and the reduced research bundle
and its first conversion. Existing conversion functions and branches are reused.
"""
from pathlib import Path
import re

root = Path("ZInQKernel/Contrib/OneProof")
older = (root / "CMFibreSplit/Fold.lean").read_text()
gr9 = (root / "CMFoldRebase/R5GR9.lean").read_text()
top = (root / "CMFoldRebase/Open77.lean").read_text()


def between(src, start, stop):
    a = src.index(start)
    return src[a:src.index(stop, a)].rstrip()


print("""import ZInQKernel.Contrib.OneProof.CMCurveOrder
import ZInQKernel.Contrib.OneProof.CMFoldRebase.Open77

/-! # Open77 with the CM fibre split discharged

Generated by `scratch/cm-curve-order/gen_fold.py`. The CM input is supplied
at open4 using the same leaves as the older fibre-split fold. The path above
open7 is the open77 GR9 path with the four remaining CM inputs threaded through.
Below the new research bundle's first conversion, the open77 bundle conversions
are reused. -/

set_option linter.style.longLine false
set_option maxHeartbeats 1000000
""")

bottom = between(older, "namespace HDec\n", "-- copied from ZInQKernel.Contrib.OneProof.CMBranch.Top2 64-69")
bottom = bottom.replace("CMInputsFS", "CMInputsOrder")
bottom = re.sub(r"_cmfs\b", "_cmorder", bottom)
bottom = bottom.replace("cmFibreSplit_of_leaves", "cmFibreSplit_of_curveOrder324")
bottom = bottom.replace("(cm-fibre-split).", "(cm-curve-order).")
print(bottom)

# Copy only theorem blocks that carried the removed CM input; all conversions
# and the other intermediate declarations remain the existing GR9 constants.
chains = re.findall(
    r"^noncomputable section\nnamespace HDec\.HSyn\.GR9\n(?:(?!^end HDec\.HSyn\.GR9$).)*?^end HDec\.HSyn\.GR9\nend$",
    gr9, re.M | re.S,
)
chains = [c for c in chains if re.search(r"^theorem .*sixContactMin_of_\w+_cm2_r5\b", c, re.M)]
assert len(chains) == 27, len(chains)
for c in chains:
    c = re.sub(r"^set_option .*\n", "", c, flags=re.M)
    c = re.sub(r"^/-- .* -/\n", "", c, flags=re.M)
    c = c.replace("CMBranch.CMInputs2", "CMBranch.FibreSplit.CMInputsOrder")
    c = re.sub(r"(sixContactMin_of_\w+)_cm2_r5\b", r"\1_cmorder", c)
    print("\n" + c)

bundle = between(top, "structure OpenResearchLeaves58CM", "/-- `OpenResearchLeaves56`")
bundle = bundle.replace("OpenResearchLeaves58CM", "OpenResearchLeaves59CMFS")
bundle, removed = re.subn(r"^  /-- cm-branch \(GLUE, open\): .*\n  cmFibreSplit : CMBranch.CMFibreSplit\n", "", bundle, flags=re.M)
assert removed == 1
conv = re.search(r"^theorem openResearchLeaves56_cm_of_58CM[^\n]*\n(?:^  [^\n]*\n)+", top, re.M).group()
conv = conv.replace("openResearchLeaves56_cm_of_58CM", "openResearchLeaves56_cm_of_59CMFS")
conv = conv.replace("OpenResearchLeaves58CM", "OpenResearchLeaves59CMFS")
assert "cmFibreSplit" not in conv

thm = between(top, "theorem sixContactMin_of_open77_cm ", "\nend HSyn")
thm = thm.replace("sixContactMin_of_open77_cm ", "sixContactMin_of_open78_cm ")
thm = thm.replace("OpenResearchLeaves58CM", "OpenResearchLeaves59CMFS")
thm = thm.replace("openResearchLeaves56_cm_of_58CM", "openResearchLeaves56_cm_of_59CMFS")
thm = thm.replace("sixContactMin_of_open48_eb_k954_cm2_r5", "sixContactMin_of_open48_eb_k954_cmorder")
thm = thm.replace(
    "⟨r.cmFibreSplit, r.fowlerProp27, r.cmjDegree, r.cmPotentialGood, r.cmHeight62,\n      CMBranch.coxProperLattice_proof⟩",
    "⟨r.fowlerProp27, r.cmjDegree, r.cmPotentialGood, r.cmHeight62⟩",
)
assert "cmFibreSplit" not in thm
print("\nnamespace HDec.HSyn\n")
print("/-- The open77 CM research bundle without the proved `cmFibreSplit` field. -/")
print(bundle)
print("\n" + conv)
print("/-- The open77 CM route with no extra hypothesis for the fibre split. -/")
print(thm)
print("\nend HDec.HSyn")
